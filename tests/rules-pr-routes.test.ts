describe("commands handed to the owner (criterion 16)", () => {
  const post = (text: string, extra: object = {}) =>
    hook("PreToolUse", "mcp__hearthbot__post_message", { text, ...extra });
  const FENCE = "```";
  test("a pull request write in a fenced block or in inline code is refused", () => {
    expect(post(`Run this:\n${FENCE}\ngh pr edit 270 --body-file b.md\n${FENCE}`).deny).toContain(
      "run it yourself",
    );
    expect(post("Run `gh pr edit 270 --body-file b.md` now").deny).toContain("run it yourself");
    expect(
      post(`${FENCE}\n$ gh api -X PATCH repos/mcthaydt/RukenApp/pulls/270 -F body=@b.md\n${FENCE}`).deny,
    ).toContain("run it yourself");
  });
  test("it is refused inside a decision's option and in an attached file", () => {
    const d = hook("PreToolUse", "mcp__hearthbot__request_decision", {
      question: "Fix it?",
      options: [{ label: "Yes", consequence: "You run `gh pr edit 270 --body-file b.md`." }],
      recommended: 0,
    });
    expect(d.deny).toContain("run it yourself");
    const file = join(scratch, "handoff.md");
    writeFileSync(file, `# Steps\n\n${FENCE}\ngh pr ready 270\n${FENCE}\n`);
    const a = post("Steps are attached.", { attached_outputs: [{ kind: "file", ref: file }] });
    expect(a.deny).toContain("run it yourself");
  });
  test("a command that needs what only the owner has is allowed, and so is plain prose", () => {
    expect(post(`${FENCE}\nwrangler secret put JOBS_SECRET --name ruken\n${FENCE}`).deny).toBeNull();
    expect(post("The hook refuses gh pr edit when it is wrong.").deny).toBeNull();
    expect(post(`${FENCE}\nGH_PAGER=cat gh api repos/mcthaydt/RukenApp/pulls/270\n${FENCE}`).deny).toBeNull();
  });
  test("the other tools of the same kind are read too", () => {
    for (const tool of ["edit_message", "post_widget"])
      expect(
        hook("PreToolUse", `mcp__hearthbot__${tool}`, { text: `${FENCE}\ngh pr close 5\n${FENCE}` }).deny,
      ).toContain("run it yourself");
  });
});

