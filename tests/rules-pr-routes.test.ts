describe("the allowlist (criterion 15)", () => {
  test("writes to GitHub's API by any program but gh are refused", () => {
    refused("curl -X POST https://api.github.com/repos/x/y/pulls");
    refused("curl -s -d '{}' https://api.github.com/repos/x/y/pulls");
    refused("wget --post-data=x https://api.github.com/repos/x/y/pulls");
    refused("G=gh; $G pr create");
    refused("${GH} pr create");
    refused("echo 5 | xargs gh pr reopen");
    refused("python -c \"import subprocess; subprocess.run(['gh', 'pr', 'create'])\"");
    refused("node -e \"require('child_process').execSync('gh pr create')\"");
    refused("python3 - <<'EOF'\nimport subprocess\nsubprocess.run(['gh','pr','close','5'])\nEOF");
    refused("find . -name x -exec gh pr close 5 \\;");
    refused("watch gh pr close 5");
    refused("parallel gh pr close ::: 5 6");
    refused("f() { gh api -X PATCH repos/mcthaydt/RukenApp; }; f");
  });
  test("gh itself, through every reading of its arguments, is still judged", () => {
    refused("gh alias set pc 'pr create'");
    refused("gh pr revert 5");
    refused("gh api graphql -f query='mutation { closePullRequest(input: {}) { clientMutationId } }'");
    refused("for i in 1 2; do gh api -X PATCH repos/mcthaydt/RukenApp; done");
    for (const shell of ["bash -c", "bash -lc", "zsh -c", "dash -c", "fish -c", "sh -c"])
      refused(`${shell} 'gh api -X PATCH repos/mcthaydt/RukenApp'`);
  });
  test("honest reads and text that only mentions these are allowed", () => {
    allowed("gh api graphql -f query='query { viewer { login } }'");
    allowed("gh pr view 5");
    allowed("GH_PAGER=cat gh pr view 5");
    allowed("env GH_PAGER=cat gh pr view 5");
    allowed('grep -n "gh pr create" CLAUDE.md');
    allowed('grep -n "api.github.com" .claude/hooks/rules.mjs');
    allowed('git commit -m "Refuse gh pr create through xargs"');
    allowed('git commit -m "Refuse curl to api.github.com"');
    allowed("curl -s https://api.github.com/repos/x/y");
    allowed('echo "run gh pr create later"');
    allowed("python3 -c \"print('ghost')\"");
    allowed("node scripts/tool.mjs");
  });
});

