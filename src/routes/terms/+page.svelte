  <h1>Terms</h1>
  <p class="note">Last updated 22 November 2026</p>
  <p>
    <strong>This is a draft.</strong> A lawyer has not checked it yet. It says how Ruken works today, and it will
    change before Ruken opens.
  </p>
  <p>These are the rules for using Ruken. By making an account, you agree to them.</p>

  <h2>What Ruken is</h2>
  <ul class="bullets">
    <li>Ruken is a place to find and play games in your browser.</li>
    <li>Watching is free. Anyone can watch the feed without an account.</li>
    <li>Playing needs a membership. Some games are free for everyone, and they say so.</li>
    <li>Makers put their games on Ruken. Each maker has a page with their games and links.</li>
  </ul>

  <h2>Who can join</h2>
  <ul class="bullets">
    <li>You must be 13 or older to make an account.</li>
    <li>Sign-up is open to phone numbers in the United States and Canada.</li>
    <li>One person, one account. Use a phone number that's yours.</li>
    <li>If you're under 18, you don't see games made for adults.</li>
  </ul>

  <h2>Your account</h2>
  <ul class="bullets">
    <li>Keep your password to yourself. What happens on your account is up to you.</li>
    <li>You can change your password, or delete your account, at any time from You.</li>
  </ul>

  <h2>Membership</h2>
  <ul class="bullets">
    <li>A membership costs $9.99 a month or $99 a year. Tax is added where it applies.</li>
    <li>There is no free trial.</li>
    <li>It renews by itself until you cancel.</li>
    <li>Cancel any time: go to You, then "Change card or cancel".</li>
    <li>
      When you cancel, you keep playing until the end of the time you paid for. Then you aren't charged again.
    </li>
    <li>Cancelling doesn't pay back time you already paid for.</li>
    <li>If you delete your account, your membership ends at once, with no money back.</li>
  </ul>

  <h2>Games on Ruken</h2>
  <ul class="bullets">
    <li>Makers make the games, not Ruken. A person at Ruken checks each game before it goes on Ruken.</li>
    <li>Games made for adults are shown only to adults.</li>
    <li>A game plays apart from Ruken. It never gets your sign-in or your account.</li>
    <li>A maker can take their game off Ruken at any time, so a game you like may go away.</li>
  </ul>
  <p><a class="go" href="/help/how-the-feed-works">How the feed works</a></p>

  <h2>What no game may have</h2>
  <ul class="bullets">
    <li><strong>No pornography.</strong></li>
    <li><strong>No gambling.</strong></li>
    <li><strong>No ads.</strong> A game can't show ads of any kind.</li>
  </ul>
  <p>A person at Ruken checks for these before a game goes on Ruken. A game that breaks them comes off.</p>

  <h2>Play fair</h2>
  <ul class="bullets">
    <li>Don't try to play games without paying, or help others do it.</li>
    <li>Don't try to break into Ruken, or into anyone's account.</li>
    <li>Don't use Ruken to break the law or to hurt anyone.</li>
    <li>Don't put anything on Ruken that you don't have the right to share.</li>
  </ul>

  <h2>If you make games</h2>
  <p>
    Before you send your first game, you agree to the maker agreement. It says what you let Ruken do with your
    game and how makers are paid. Where this page and the agreement differ, the agreement wins.
  </p>
  <p><a class="go" href="/legal/maker-agreement">Read the maker agreement</a></p>

